        if ( $rec->is_gerente_contable() )
        {
            parent::mark_deleted( $id ); // TODO: Change the autogenerated stub

            foreach ( $recibos as $r )
                $r->update_cartera();
				
				$oportunidades = $r->get_linked_beans( 'veta_recibo_opportunities', 'Opportunity' );

				foreach ( $oportunidades as $op )
				{
					$o = $op;
					error_log('ALFONSO - OPPORTUNIDAD - DELETE PAGO ' . $o->name);
				}
				
				$r->actualizar_oportunidad($o);
        }
        else
        {
            $this->redireccionar( 'Solo un gerente contable puede eliminar un recibo', $id );
        }
    }

    public function redireccionar( $msg, $registro )
    {
        if ( ! empty( $registro ) )
        {
            $aux = "<script>
                      var registro='" . $registro . "';";

            $aux .= "alert('" . $msg . "');
                    window.location = 'index.php?module=NVC_Deposit_Company&action=DetailView&record=' + registro;
                 </script>";

            echo $aux;
        }
        else
        {
            echo "<script>alert('" . $msg . "')</script>";
        }

        exit;
    }
	
	function deleteAttachment($isduplicate = "false")
    {
        if ($this->ACLAccess('edit')) {
            if ($isduplicate == "true") {
                return true;
            }
            $removeFile = "upload://{$this->id}";
        }

        if (file_exists($removeFile)) {
            if (!unlink($removeFile)) {
                $GLOBALS['log']->error("*** Could not unlink() file: [ {$removeFile} ]");
            } else {
                $this->uploadfile = '';
                $this->filename = '';
                $this->file_mime_type = '';
                $this->file = '';
                $this->save();
                return true;
            }
        } else {
            $this->uploadfile = '';
            $this->file_mime_type = '';
            $this->file = '';
            $this->save();
            return true;
        }
        return false;
    }
	
