	/**
     * Establece el estado del requerimiento asociando como Cerrado debido a que se realizo un abono
     */
    private function cerrar_requerimiento()
    {
        $sql = "UPDATE veta_requerimiento_cstm 
                INNER JOIN veta_requerimiento_veta_presupuesto_c ON veta_requerimiento_veta_presupuesto_c.veta_requerimiento_veta_presupuestoveta_requerimiento_ida = veta_requerimiento_cstm.id_c AND veta_requerimiento_veta_presupuesto_c.deleted = 0 
                INNER JOIN veta_presupuesto ON veta_presupuesto.id = veta_requerimiento_veta_presupuesto_c.veta_requerimiento_veta_presupuestoveta_presupuesto_idb AND veta_presupuesto.deleted = 0 
                INNER JOIN veta_recibo_veta_presupuesto_c ON veta_recibo_veta_presupuesto_c.veta_recibo_veta_presupuestoveta_presupuesto_ida = veta_presupuesto.id AND veta_recibo_veta_presupuesto_c.deleted = 0 
                INNER JOIN veta_recibo ON veta_recibo.id = veta_recibo_veta_presupuesto_c.veta_recibo_veta_presupuestoveta_recibo_idb AND veta_recibo.deleted = 0 
                INNER JOIN veta_recibo_nvc_deposit_company_1_c ON veta_recibo_nvc_deposit_company_1_c.veta_recibo_nvc_deposit_company_1veta_recibo_ida = veta_recibo.id AND veta_recibo_nvc_deposit_company_1_c.deleted = 0 
                INNER JOIN nvc_deposit_company ON nvc_deposit_company.id = veta_recibo_nvc_deposit_company_1_c.veta_recibo_nvc_deposit_company_1nvc_deposit_company_idb AND nvc_deposit_company.deleted = 0
                SET company_stage_c = 'Cerrado'  
                WHERE nvc_deposit_company.id = '" . $this->id . "'";
				
				//company_stage_c

        $this->db->query( $sql );
    }

    private function update_recibo()
    {
        $id      = null;
        $recibos = $this->get_linked_beans( 'veta_recibo_nvc_deposit_company_1', 'NVC_Deposit_company' );

        foreach ( $recibos as $r )
        {
            $r->update_cartera();
			
			$oportunidades = $r->get_linked_beans( 'veta_recibo_opportunities', 'Opportunity' );

			foreach ( $oportunidades as $op )
			{
				$o = $op;
				error_log('ALFONSO - OPPORTUNIDAD - UPDATE RECIBO ' . $o->name);
			}
			
			if (isset ($o)) {
				$r->actualizar_oportunidad($o);
			}
			
            $id = $r->id;
        }

        return $id;
    }

    public function mark_deleted( $id )
    {
        $rec     = new Veta_Recibo();
